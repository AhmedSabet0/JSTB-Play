#!/bin/bash
# Builds JSTB for Google Play (Android App Bundle .aab).
#
#   ./build.sh               -> out/JSTB.aab (Android App Bundle signed with keystore)
#   APK=1 ./build.sh         -> out/JSTB.apk (Universal test APK for local testing)
#
#   SERVER_URL=https://DOMAIN  builds the server into the app (optional)
#   VERSION_CODE=7 VERSION_NAME=3.4 override the manifest's version
#
# Needs: JDK 17+, aapt2, dalvik-exchange (dx), zipalign, apksigner, jarsigner, android-34.jar, bundletool.jar.
set -euo pipefail
cd "$(dirname "$0")"
unset JAVA_TOOL_OPTIONS
SERVER_URL=${SERVER_URL:-}
ANDROID_JAR=${ANDROID_JAR:-/home/claude/android-tools/android-34.jar}
BUNDLETOOL=${BUNDLETOOL:-/home/claude/android-tools/bundletool/bundletool.jar}
AAPT2=${AAPT2:-$(find "${ANDROID_HOME:-}" -name aapt2 2>/dev/null | sort -V | tail -n 1 || true)}
AAPT2=${AAPT2:-aapt2}
KS=${KEYSTORE:-keystore/autoapply.jks}
KS_PASS=${KS_PASS:-autoapply}
OUT=out

SERVER_URL=${SERVER_URL%/}
if [ -n "$SERVER_URL" ] && ! [[ "$SERVER_URL" =~ ^https://[A-Za-z0-9.-]+(:[0-9]+)?$ ]]; then
  echo "SERVER_URL must look like https://example.com" >&2; exit 1
fi

if [ ! -f "$KS" ]; then
  if [ -z "${NEW_KEY:-}" ]; then
    echo "No signing key at $KS. Point KEYSTORE=/path/to/keystore.jks at your key." >&2
    exit 1
  fi
  mkdir -p "$(dirname "$KS")"
  keytool -genkeypair -keystore "$KS" -storepass "$KS_PASS" -keypass "$KS_PASS" -alias autoapply \
    -keyalg RSA -keysize 2048 -validity 20000 -dname "CN=JSTB, O=JSTB" >/dev/null
  echo "Made a new signing key: $KS"
fi

rm -rf "$OUT" && mkdir -p "$OUT/gen/com/autoapply/bot/app" "$OUT/classes" "$OUT/res" "$OUT/assets"

cp -r assets/. "$OUT/assets/"
cp AndroidManifest.xml "$OUT/AndroidManifest.xml"
cp -r res/. "$OUT/res/"

[ -n "${VERSION_CODE:-}" ] && sed -i "s/android:versionCode=\"[0-9]*\"/android:versionCode=\"$VERSION_CODE\"/" "$OUT/AndroidManifest.xml"
[ -n "${VERSION_NAME:-}" ] && sed -i "s/android:versionName=\"[^\"]*\"/android:versionName=\"$VERSION_NAME\"/" "$OUT/AndroidManifest.xml"

cat > "$OUT/gen/com/autoapply/bot/app/BuildConfig.java" <<JAVA
package com.autoapply.bot.app;

/** Generated by build.sh. */
public final class BuildConfig {
    public static final String FLAVOR = "play";
    public static final String SERVER_URL = "$SERVER_URL";
    public static final String FILES_AUTHORITY = "com.autoapply.bot.files";

    private BuildConfig() {
    }
}
JAVA

compile_java() {
  javac --release 8 -Xlint:-options -nowarn -encoding UTF-8 -classpath "$ANDROID_JAR" -d "$OUT/classes" \
    $(find src "$OUT/gen" -name "*.java")
  dalvik-exchange --dex --min-sdk-version=24 --output="$OUT/classes.dex" "$OUT/classes"
}

# Android App Bundle (resources in protobuf format from aapt2, assembled by bundletool)
"$AAPT2" compile --dir "$OUT/res" -o "$OUT/res.zip"
"$AAPT2" link --proto-format -o "$OUT/base-proto.apk" -I "$ANDROID_JAR" --manifest "$OUT/AndroidManifest.xml" \
  -A "$OUT/assets" --java "$OUT/gen" --auto-add-overlay "$OUT/res.zip"
compile_java

mkdir -p "$OUT/module"
(cd "$OUT/module" && unzip -q ../base-proto.apk && mkdir -p manifest dex && mv AndroidManifest.xml manifest/ \
  && cp ../classes.dex dex/ && zip -q -r -X ../base.zip .)
java -jar "$BUNDLETOOL" build-bundle --modules="$OUT/base.zip" --output="$OUT/JSTB.aab"

jarsigner -keystore "$KS" -storepass "$KS_PASS" -keypass "$KS_PASS" -sigalg SHA256withRSA -digestalg SHA-256 \
  "$OUT/JSTB.aab" autoapply >/dev/null
jarsigner -verify "$OUT/JSTB.aab" | tail -1
ls -la "$OUT/JSTB.aab"

if [ -n "${APK:-}" ]; then
  rm -f "$OUT/app.apks"
  java -jar "$BUNDLETOOL" build-apks --bundle="$OUT/JSTB.aab" --output="$OUT/app.apks" --mode=universal \
    --ks="$KS" --ks-pass="pass:$KS_PASS" --ks-key-alias=autoapply --key-pass="pass:$KS_PASS"
  (cd "$OUT" && unzip -q -o app.apks universal.apk && mv universal.apk JSTB.apk)
  ls -la "$OUT/JSTB.apk"
fi
